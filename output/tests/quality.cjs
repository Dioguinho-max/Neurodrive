const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const code = fs.readFileSync(path.join(__dirname, '../neurodrive-hud.js'), 'utf8');
const storage = new Map();
const host = { localStorage: { getItem: (key) => storage.get(key), setItem: (key, value) => storage.set(key, value) } };
new Function('window', code)(host);
const single = {};
let applied;
host.bindNeuroQuality(single, (value) => { applied = value; });
assert.equal(single.value, 'performance');
single.value = 'high'; single.onchange();
assert.equal(applied, 'high');
const online = {};
host.bindNeuroQuality(online, () => {});
assert.equal(online.value, 'high', 'Online recupera a preferência salva no single-player');
online.value = 'performance'; online.onchange();
const reopened = {};
host.bindNeuroQuality(reopened, () => {});
assert.equal(reopened.value, 'performance');
single.value = 'ultra'; single.onchange();
assert.equal(applied, 'ultra');
host.bindNeuroQuality(reopened, () => {});
assert.equal(reopened.value, 'ultra', 'Super alto permanece salvo ao reabrir o jogo');
storage.set('neurodrive-graphics', 'invalid');
host.bindNeuroQuality(reopened, () => {});
assert.equal(reopened.value, 'performance');
Object.defineProperty(host, 'localStorage', { get() { throw new Error('Armazenamento bloqueado'); } });
host.bindNeuroQuality(reopened, (value) => { applied = value; });
reopened.value = 'high'; reopened.onchange();
assert.equal(applied, 'high', 'Qualidade ainda pode ser alterada com armazenamento bloqueado');
console.log('OK: preferência compartilhada, recarregamento, valor inválido e armazenamento bloqueado.');
