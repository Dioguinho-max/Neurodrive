const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const element=()=>({children:[],hidden:false,setAttribute(){},append(...items){this.children.push(...items);}});
const host=element(),window={},document={createElement:element};
new Function('window','document',fs.readFileSync(path.join(__dirname,'../neurodrive-radio.js'),'utf8'))(window,document);
const radio=window.createNeuroRadio(host), panel=host.children[0], text=panel.children[1];
const car={completedLaps:0,weatherMode:'changing',rainIntensity:0,tyreLife:1,tyreCompound:'dry'};
const state={key:'solo',phase:'racing',laps:3,qualifying:false,elapsed:22};
radio.update(car,state,true,0);assert(text.textContent.includes('prevista'));assert.equal(panel.hidden,false);
radio.update(car,state,true,6000);assert.equal(panel.hidden,true);
radio.update(car,state,true,17000);assert.equal(panel.hidden,true,'Forecast never repeats');
car.rainIntensity=.3;state.elapsed=45;radio.update(car,state,true,18000);assert(text.textContent.includes('começou'));
car.tyreBurst=true;radio.update(car,state,true,18001);assert(text.textContent.includes('furado'),'Puncture interrupts noncritical message');
car.tyreBurst=false;car.pitStops=1;radio.update(car,state,true,18002);assert.equal(panel.hidden,true,'Pit repairs clear stale warnings');
car.tyreWearEnabled=true;car.tyreLife=.2;radio.update(car,state,true,35000);assert(text.textContent.includes('limite'));
radio.update(car,state,false,35001);assert.equal(panel.hidden,true,'Pause hides message');
state.key='race-2';state.qualifying=true;car.tyreLife=1;car.weatherMode='dry';car.completedLaps=2;
radio.update(car,state,true,40000);assert.equal(panel.hidden,true,'No final-race-lap message in qualifying');
state.key='race-3';state.qualifying=false;radio.update(car,state,true,41000);assert(text.textContent.includes('Última'));
state.phase='finished';radio.update(car,state,true,42000);assert.equal(panel.hidden,true);
state.key='drift';state.phase='racing';state.drift=true;radio.update(car,state,true,43000);assert.equal(panel.hidden,true);
console.log('OK: radio priority, expiry, cooldown, pit repairs, stage resets, pause and drift exclusion.');
