const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const THREE=require('../vendor/three.min.js');
const ctx=new Proxy({}, {get:(target,key)=>target[key]||(()=>{}),set:(target,key,value)=>(target[key]=value,true)});
const document={documentElement:{lang:'pt-BR'},createElement:()=>({getContext:()=>ctx})},window={};
vm.runInNewContext(fs.readFileSync('output/neurodrive-cockpit-3d.js','utf8'),{window,document,performance});
const camera=new THREE.PerspectiveCamera(),cabin=window.createNeuroCockpit3D(THREE,camera);
const car={speed:3,steering:.8,rpm:6000,gear:1,manual:true,tyreLife:.6};
const wheel=cabin.root.getObjectByName('cabin-steering-wheel'),lever=cabin.root.getObjectByName('cabin-gear-lever');
cabin.update(car,true,100);assert(cabin.root.visible);assert(wheel.rotation.z<0);assert(lever.rotation.x<0);
for(let i=0;i<30;i++)cabin.update({...car,gear:6},true,200+i*90);
assert(lever.rotation.x>0&&lever.rotation.z<0,'Sixth gear moves lever across and back');
for(let i=0;i<80;i++)cabin.update({...car,manual:false,gear:i%6+1},true,4000+i*90);
assert(Math.abs(lever.rotation.x)<1e-6&&Math.abs(lever.rotation.z)<1e-6,'Automatic lever remains parked');
const throttle=cabin.root.getObjectByName('cabin-throttle-pedal'),brake=cabin.root.getObjectByName('cabin-brake-pedal');
for(let i=0;i<30;i++)cabin.update({...car,throttle:.5,brake:0},true,12000+i*17);
assert(Math.abs(throttle.rotation.x-.17)<.002&&brake.rotation.x===0,'Analog throttle depresses only accelerator');
for(let i=0;i<30;i++)cabin.update({...car,throttle:0,brake:1},true,13000+i*17);
assert(throttle.rotation.x<.001&&Math.abs(brake.rotation.x-.24)<.002,'Braking releases accelerator and depresses brake');
for(let i=0;i<30;i++)cabin.update({...car,throttle:0,brake:0},true,14000+i*17);
assert(brake.rotation.x<.001,'Released pedals return smoothly to rest');
const originalTarget={},seen=[],views=[];
let activeTarget=originalTarget;
const renderer={shadowMap:{autoUpdate:true},getRenderTarget:()=>activeTarget,setRenderTarget:t=>{activeTarget=t;},clear(){},render(scene,view){
  assert(!cabin.root.visible,'Mirror pass excludes cabin to prevent feedback');
  assert(!this.shadowMap.autoUpdate,'Mirror pass reuses shadows');
  assert(view.getWorldDirection(new THREE.Vector3()).x<-.8,'Mirror camera looks behind car');
  seen.push(activeTarget);views.push(view.position.clone());
}};
const state={...car,x:20,y:40,angle:0};
cabin.renderMirrors(renderer,new THREE.Scene(),state,'performance',10000);
assert.equal(seen.length,1,'Only one extra scene pass per frame');
cabin.renderMirrors(renderer,new THREE.Scene(),state,'performance',10060);
cabin.renderMirrors(renderer,new THREE.Scene(),state,'performance',10120);
assert.equal(seen.length,3);assert.equal(new Set(seen).size,3);
assert.notEqual(views[0].z,views[1].z);assert.notEqual(views[1].z,views[2].z);
assert.equal(activeTarget,originalTarget);assert(renderer.shadowMap.autoUpdate&&cabin.root.visible);
cabin.renderMirrors(renderer,new THREE.Scene(),state,'performance',10150);assert.equal(seen.length,3,'Updates are throttled');
const render=renderer.render;renderer.render=()=>{throw Error('test render failure');};
assert.throws(()=>cabin.renderMirrors(renderer,new THREE.Scene(),state,'performance',10200));
assert.equal(activeTarget,originalTarget);assert(renderer.shadowMap.autoUpdate&&cabin.root.visible,'Render failure restores main view state');
renderer.render=render;
cabin.update(null,false);assert(!cabin.root.visible,'Camera exit requires no car state');
cabin.renderMirrors(renderer,new THREE.Scene(),state,'performance',11000);assert.equal(seen.length,3,'No mirrors outside cockpit');
let disposed=0;cabin.root.traverse(p=>p.geometry?.addEventListener('dispose',()=>disposed++));
cabin.dispose();assert(disposed>30);assert(!camera.children.includes(cabin.root));
console.log('OK: cabin, gear lever, three rear viewpoints, update budget, render-state restoration and disposal.');
